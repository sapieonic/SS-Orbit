-- Identity: HO users, field assistants, devices and sessions.
-- Farmers sign in by phone; their profile lives in the farmers module and
-- their sessions/devices live here, keyed by subject_kind + subject_id.

-- +goose Up
CREATE TABLE ho_users (
  id            uuid PRIMARY KEY,
  email         citext NOT NULL UNIQUE,
  name          text NOT NULL,
  password_hash text NOT NULL,
  totp_secret   text,                       -- set during enrolment
  totp_enabled  boolean NOT NULL DEFAULT false,
  role          text NOT NULL CHECK (role IN ('admin', 'agronomy', 'finance', 'ops')),
  district_ids  uuid[] NOT NULL DEFAULT '{}', -- area scope; empty means all districts
  status        text NOT NULL DEFAULT 'active' CHECK (status IN ('invited', 'active', 'disabled')),
  last_login_at timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER ho_users_touch BEFORE UPDATE ON ho_users FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

-- One login per person (FA-01; FA-02 resolved as per-person login + territory hand-over).
CREATE TABLE field_assistants (
  id                   uuid PRIMARY KEY,
  code                 text NOT NULL UNIQUE,  -- login ID, e.g. FA-KDP-014
  name                 text NOT NULL,
  name_te              text,
  phone                text NOT NULL,         -- E.164, +91XXXXXXXXXX
  password_hash        text NOT NULL,
  must_change_password boolean NOT NULL DEFAULT true,
  level                text NOT NULL CHECK (level IN ('village', 'mandal', 'district')),
  languages            text[] NOT NULL DEFAULT '{te}',
  working_hours        text,
  photo_key            text,
  status               text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'leaving', 'inactive')),
  last_login_at        timestamptz,
  last_sync_at         timestamptz,
  created_by           uuid REFERENCES ho_users (id),
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER field_assistants_touch BEFORE UPDATE ON field_assistants FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

CREATE TABLE devices (
  id            uuid PRIMARY KEY,
  subject_kind  text NOT NULL CHECK (subject_kind IN ('farmer', 'fa')),
  subject_id    uuid NOT NULL,
  device_key    text NOT NULL,              -- install ID generated by the app
  model         text,
  os_version    text,
  app_version   text,
  push_token    text,                       -- FCM/APNs token for push notifications (messaging)
  revoked_at    timestamptz,                -- revoked device wipes itself at next sync/unlock
  revoke_reason text,
  last_seen_at  timestamptz,
  last_sync_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (subject_kind, subject_id, device_key)
);

-- Refresh-token sessions with rotation. Reuse of a rotated token revokes the family.
CREATE TABLE sessions (
  id                 uuid PRIMARY KEY,
  subject_kind       text NOT NULL CHECK (subject_kind IN ('farmer', 'fa', 'ho')),
  subject_id         uuid NOT NULL,
  device_id          uuid REFERENCES devices (id),
  family_id          uuid NOT NULL,
  refresh_token_hash bytea NOT NULL UNIQUE,  -- sha256 of the opaque token
  expires_at         timestamptz NOT NULL,
  rotated_at         timestamptz,
  revoked_at         timestamptz,
  user_agent         text,
  ip                 inet,
  created_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_subject_idx ON sessions (subject_kind, subject_id) WHERE revoked_at IS NULL;
CREATE INDEX sessions_family_idx ON sessions (family_id);


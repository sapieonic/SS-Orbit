#!/usr/bin/env python3
"""Write contracts/ENDPOINTS.md: every API operation grouped by surface, from contracts/openapi/*.yaml.

Run from the repo root: python3 tools/list-endpoints.py   (needs PyYAML)
"""
import pathlib
import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPECS = ROOT / "contracts" / "openapi"
SURFACES = [
    ("/v1/auth/", "Auth (no token)"),
    ("/v1/farmer/", "Farmer app (farmer token)"),
    ("/v1/fa/", "FA app (fa token)"),
    ("/v1/admin/", "HO portal (ho token)"),
    ("/v1/web/", "Farmer web pages (signed link token)"),
    ("/hooks/", "Partner webhooks"),
]


def main():
    rows = []
    for spec in sorted(SPECS.glob("*.yaml")):
        if spec.name.startswith("_"):
            continue
        doc = yaml.safe_load(spec.read_text())
        for path, ops in (doc.get("paths") or {}).items():
            for method, op in ops.items():
                if method not in ("get", "post", "put", "patch", "delete"):
                    continue
                summary = (op.get("summary") or op.get("operationId") or "").strip().replace("|", "/")
                rows.append((path, method.upper(), spec.stem, op.get("operationId", ""), summary))

    out = ["# API endpoints", "",
           "Generated by `tools/list-endpoints.py` from `contracts/openapi/*.yaml`. Don't edit by hand; re-run it after",
           "changing a spec. The specs are the source of truth (request/response schemas, error codes).", ""]
    for prefix, title in SURFACES:
        group = sorted(r for r in rows if r[0].startswith(prefix))
        if not group:
            continue
        out += [f"## {title}", "", "| Method | Path | Spec | operationId | Summary |", "|---|---|---|---|---|"]
        out += [f"| {m} | `{p}` | {s} | {o} | {d} |" for p, m, s, o, d in group]
        out.append("")
    other = sorted(r for r in rows if not any(r[0].startswith(p) for p, _ in SURFACES))
    if other:
        out += ["## Other", "", "| Method | Path | Spec | operationId | Summary |", "|---|---|---|---|---|"]
        out += [f"| {m} | `{p}` | {s} | {o} | {d} |" for p, m, s, o, d in other]
        out.append("")
    (ROOT / "contracts" / "ENDPOINTS.md").write_text("\n".join(out))
    print(f"wrote contracts/ENDPOINTS.md ({len(rows)} operations)")


if __name__ == "__main__":
    main()
